#!/usr/bin/env bash
# Recreate the Stripe TEST webhook endpoint and update STRIPE_WEBHOOK_SECRET.
#
# Why this exists: after the deposit was paid on 2026-08-13, Stripe reported the
# checkout session as complete and paid — and `stripe.webhookEndpoints.list()` returned
# ZERO endpoints. Every event carried pending_webhooks=0, meaning Stripe had nowhere to
# deliver. The endpoint the installer created no longer exists, so the whsec_ in .env
# belongs to a deleted endpoint and no payment can ever reach SAOS.
#
# Same shape as install-stripe-test.sh: you never see or paste the signing secret. It is
# generated by Stripe, captured from the API response, and written straight to .env.
#
# Run on the server:
#   bash /opt/saos/scripts/repair-stripe-webhook.sh

set -euo pipefail

ENV_FILE=/opt/saos/.env
URL=https://api.sotoaccounting.com/webhooks/stripe

green() { printf '  \033[32mPASS\033[0m  %s\n' "$1"; }
red()   { printf '  \033[31mFAIL\033[0m  %s\n' "$1"; }

SK=$(grep -E '^STRIPE_SECRET_KEY=' "$ENV_FILE" | cut -d= -f2-)
if [ -z "${SK:-}" ]; then red "No STRIPE_SECRET_KEY in $ENV_FILE"; exit 1; fi
case "$SK" in
  sk_test_*) green "using the TEST secret key already in .env (never printed)";;
  *) red "STRIPE_SECRET_KEY is not an sk_test_ key — refusing to touch live config"; exit 1;;
esac

echo
echo "1. Existing endpoints"
EXISTING=$(curl -s https://api.stripe.com/v1/webhook_endpoints -u "$SK:" \
  | grep -o '"url": *"[^"]*"' | sed 's/.*"url": *"//; s/"$//' || true)
if [ -z "$EXISTING" ]; then
  echo "     none registered — that is the bug"
else
  echo "     $EXISTING"
fi

echo
echo "2. Creating the endpoint"
RESP=$(curl -s https://api.stripe.com/v1/webhook_endpoints -u "$SK:" \
  -d "url=$URL" \
  -d "enabled_events[]=checkout.session.completed" \
  -d "enabled_events[]=payment_intent.payment_failed" \
  -d "description=SAOS deposit + invoice payments (test)")

EP_ID=$(printf '%s' "$RESP" | grep -o '"id": *"we_[^"]*"' | head -1 | sed 's/.*"we_/we_/; s/"$//')
SECRET=$(printf '%s' "$RESP" | grep -o '"secret": *"whsec_[^"]*"' | head -1 | sed 's/.*"whsec_/whsec_/; s/"$//')

if [ -z "${EP_ID:-}" ] || [ -z "${SECRET:-}" ]; then
  red "Stripe did not return an endpoint and secret. Raw response:"
  printf '%s\n' "$RESP" | head -c 500
  exit 1
fi
green "endpoint $EP_ID created; signing secret captured (…${SECRET: -4}) — you never had to see it"

echo
echo "3. Writing $ENV_FILE"
cp "$ENV_FILE" "$ENV_FILE.bak.$(date +%Y%m%d%H%M%S)"
if grep -qE '^STRIPE_WEBHOOK_SECRET=' "$ENV_FILE"; then
  sed -i "s|^STRIPE_WEBHOOK_SECRET=.*|STRIPE_WEBHOOK_SECRET=$SECRET|" "$ENV_FILE"
else
  printf 'STRIPE_WEBHOOK_SECRET=%s\n' "$SECRET" >> "$ENV_FILE"
fi
# STRIPE_MODE is reset to stub by every deploy, because .env.production ships a literal
# value and merge-env only protects BLANK repo values. Re-assert it here.
sed -i 's|^STRIPE_MODE=.*|STRIPE_MODE=live|' "$ENV_FILE"
green "STRIPE_WEBHOOK_SECRET updated and STRIPE_MODE=live re-asserted (values not shown)"

echo
echo "4. Restarting the API"
cd /opt/saos
docker compose -f docker-compose.yml -f docker-compose.prod.yml up -d api >/dev/null 2>&1
sleep 10
if [ "$(docker inspect saos-api-1 --format '{{.State.Health.Status}}' 2>/dev/null || echo starting)" = "unhealthy" ]; then
  red "saos-api-1 is unhealthy — check: docker logs saos-api-1 --tail 40"
  exit 1
fi
green "saos-api-1 restarted"

echo
echo "5. Verifying"
docker cp /opt/saos/scripts/verify-stripe.mjs saos-api-1:/app/verify-stripe.mjs >/dev/null
docker exec saos-api-1 node /app/verify-stripe.mjs || true
docker exec saos-api-1 rm -f /app/verify-stripe.mjs >/dev/null 2>&1 || true

echo
echo "Done. Tell Claude and he will replay the checkout.session.completed event"
echo "from Stripe so the invoice is settled by the REAL webhook path, not by hand."
